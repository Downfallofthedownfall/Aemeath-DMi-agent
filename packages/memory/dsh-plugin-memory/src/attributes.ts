/**
 * 属性归一化（**步骤顺序不可换**，与参考对象一致）：
 *   1) 非 string → ''
 *   2) 全角空格 U+3000 → ' '；全角 ASCII U+FF01..U+FF5E → 码点 - 65248
 *   3) trim
 *   4) 去掉**全部内部空白**（\s+ → ''）
 *   5) 查别名表收敛（表键必须无空白，因此必须先去空白）
 *   6) 超长截断（护栏，防异常长属性名污染键比较）
 * @param attr 原始属性名（未知类型一律归为 ''）
 */
export function canonicalAttr(attr: unknown): string {
  if (typeof attr !== 'string') return '';
  let out = '';
  for (const ch of attr) {
    const code = ch.codePointAt(0) as number;
    if (code === 0x3000) out += ' ';
    else if (code >= 0xff01 && code <= 0xff5e) out += String.fromCodePoint(code - 0xfee0);
    else out += ch;
  }
  const collapsed = out.trim().replace(/\s+/g, '');
  if (!collapsed) return '';
  return (ATTR_ALIASES.get(collapsed) ?? collapsed).slice(0, ATTR_MAX_CHARS);
}

/** 该属性是否属于已知规范词表（面板/调试用，不影响比较——比较一律走归一化后的字面量）。 */
export function isKnownAttr(attr: unknown): boolean {
  return CANONICAL_ATTRS.includes(canonicalAttr(attr));
}
